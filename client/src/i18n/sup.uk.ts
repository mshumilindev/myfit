import type { supEn } from './sup.en';

const p3 = (n: number, one: string, few: string, many: string): string => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};
/** "1 ложка", "1.5 ложки", "5 ложок": a fraction takes the singular genitive. */
const counted = (n: string, one: string, few: string, many: string): string => {
  const v = Number(n);
  return `${n} ${Number.isInteger(v) ? p3(v, one, few, many) : few}`;
};

