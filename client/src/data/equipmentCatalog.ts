/**
 * Equipment catalog — a curated, offline taxonomy of gym gear, far finer than
 * the coarse per-exercise `EquipmentId` tag. Each item carries the muscles it
 * trains (for machines/free weights), the notable brands that make it, a short
 * note, and the coarse `cls` it satisfies so exercise filtering ("can I do this
 * at my gym?") maps straight onto the existing exercise↔equipment tags.
 *
 * Brand NAMES are used nominatively (to describe the gear), no logos. This is a
 * living dataset — grow it; it is intentionally broad, not every SKU on earth.
 */
import type { MuscleGroup } from './exercises';
import type { EquipmentId } from './equipment';

export type EquipCategory =
  | 'barbell'
  | 'dumbbell'
  | 'kettlebell'
  | 'plate'
  | 'rack'
  | 'bench'
  | 'machine' // selectorized (pin-loaded) resistance machines
  | 'plateLoaded' // plate-loaded / iso-lateral ("Hammer") machines
  | 'cable'
  | 'cardio'
  | 'band'
  | 'suspension'
  | 'conditioning' // strongman / functional / GPP
  | 'accessory' // bars attachments, belts, grips, boxes
  | 'recovery';

export type LoadType =
  'selectorized' | 'plate' | 'fixed' | 'adjustable' | 'bodyweight' | 'motorized' | 'none';

export interface EquipmentItem {
  id: string;
  name: string;
  category: EquipCategory;
  /** Coarse class it satisfies, so exercises tagged with it filter by gym. */
  cls: EquipmentId;
  /** Primary muscles it trains (empty for pure cardio/recovery/support). */
  muscles: MuscleGroup[];
  /** Notable brands that make this type (nominative, no logos). */
  brands?: string[];
  loadType?: LoadType;
  /** One-line note: what it is / why it's useful. */
  info?: string;
  /** Extra searchable keywords / aliases. */
  aka?: string[];
}

